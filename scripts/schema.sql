-- The whole schema, applied with `create ... if not exists` by the app on its first query
-- (lib/db.ts) and by scripts/migrate-sqlite.mjs before it imports the old SQLite rows.
create table if not exists events (
  id bigint generated by default as identity primary key,
  at timestamptz not null,
  day date not null,                   -- UTC calendar day
  vid text not null,                   -- daily visitor id: hash of day + ip + user agent + secret
  path text not null,
  referrer text not null default '',
  width integer,
  ua text not null default ''
);
create index if not exists events_day on events(day);
create index if not exists events_day_vid on events(day, vid);
create index if not exists events_path on events(path) where path like '/articles/%';
create table if not exists quotes (
  id bigint generated by default as identity primary key,
  at timestamptz not null,
  day date not null,
  vid text not null default '',
  name text not null,
  business text not null,
  email text not null,
  notes text not null default '',
  items jsonb not null default '[]',   -- offer ids
  total integer not null,
  ua text not null default ''
);
create index if not exists quotes_day on quotes(day);
create table if not exists settings (
  key text primary key,
  value text not null
);
-- a paid order: the admin creates it after payment and sends the customer its unique upload link
create table if not exists orders (
  id bigint generated by default as identity primary key,
  token text not null unique,          -- the unique link, 24 url-safe chars
  created_at timestamptz not null,
  business text not null,
  name text not null,
  email text not null,
  items jsonb not null default '[]',
  note text not null default '',
  status text not null default 'awaiting' check (status in ('awaiting', 'received', 'done'))
);
-- the quote request an order was made from, when it was; null for orders typed in by hand
alter table orders add column if not exists quote_id bigint references quotes(id) on delete set null;
create index if not exists orders_quote on orders(quote_id);
create table if not exists uploads (
  id bigint generated by default as identity primary key,
  order_id bigint not null references orders(id) on delete cascade,
  at timestamptz not null,
  kind text not null,                  -- logo | product | other
  filename text not null,              -- the customer's file name
  stored text not null,                -- file name on disk under data/uploads/<order_id>/
  size bigint not null,
  mime text not null default '',
  note text not null default ''
);
create index if not exists uploads_order on uploads(order_id);
-- articles written in the dashboard; body is Markdown, cover is a file under data/articles/
create table if not exists articles (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  summary text not null default '',
  body text not null default '',
  cover text not null default '',      -- file name on disk, '' for none
  cover_alt text not null default '',
  status text not null default 'draft' check (status in ('draft', 'published')),
  created_at timestamptz not null,
  updated_at timestamptz not null,
  published_at timestamptz             -- set the first time it is published
);
-- dashboard users; the first one is seeded from ADMIN_EMAIL + ADMIN_PASSWORD when the table is empty
create table if not exists admins (
  id bigint generated by default as identity primary key,
  email text not null unique,          -- stored lower-case
  name text not null default '',
  password_hash text not null,         -- scrypt$<salt>$<hash>
  created_at timestamptz not null default now(),
  last_login_at timestamptz
);
